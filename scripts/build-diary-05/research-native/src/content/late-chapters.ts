export const lateCampaignDungeons: DungeonDef[] = routes.flatMap((route, chapter) => route.map((stage, position): DungeonDef => {
  const chapterDef = lateCampaignChapters[chapter]!;
  const main = chapter === 0 ? 'hollow-keeper' : chapter === 1 ? 'veil-priestess' : 'stone-drake';
  const escortPool = lateEscorts.filter(id => id !== main).concat(['pale-wolf', 'moon-moth']);
  const escortOffset = position === route.length - 1 ? 0 : position % escortPool.length;
  const escorts = [escortPool[escortOffset]!, escortPool[(escortOffset + 1) % escortPool.length]!];
  const approaches = Array.from({ length: chapter === 0 ? 2 : 3 }, (_, wave) => lateApproaches[(position + wave) % lateApproaches.length]!);
  const material = stage[0] === 'register-return' ? 'name-register:rare' : stage[0] === 'infirmary-handover' ? 'herbal-cloth:rare' : stage[0] === 'lantern-return' ? 'night-watch:rare' : stage[0] === 'two-signatures' ? 'night-thread:rare' : undefined;
  return {
    id: stage[0], chapterId: chapterDef.id, kind: 'normal', name: stage[1], subtitle: chapterDef.subtitle,
    description: `第${chapter + 5}章・${position + 1}。${stage[2]}`, artId: 'cathedral', published: true,
    previousDungeonId: position ? route[position - 1]![0] : chapter ? routes[chapter - 1]!.at(-1)![0] : 'zakuro-procession',
    waves: [...approaches.map(ids => ids.map(characterId => ({ characterId }))), [{ characterId: main, boss: true }, ...escorts.map(characterId => ({ characterId }))]],
    bossScale: { hp: 2000, attack: lateBossAttack[chapter * 10 + position]! },
    bossStrike: { every: 3, power: 220 + Math.round((chapter * 10 + position) * 80 / 29), name: chapter === 0 ? '返還印の重撃' : chapter === 1 ? '帰路を閉じる灯' : '契印の一閃', target: 'pilot', windup: { breakPercent: 8, weakenedPower: 90, recoveryPercent: 30 } },
    ...(material ? { bossLoot: { guaranteed: [{ materialId: material, count: 1 }] } } : {}),
    narrative: { before: stage[2], after: stage[3] },
  };
}));

